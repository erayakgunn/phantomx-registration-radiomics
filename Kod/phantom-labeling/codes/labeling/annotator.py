"""Run the annotation pipeline on a labeled series folder.

A labeled folder produced by ``labeling.labeler`` has this layout::

    <labeled_root>/<labeled_name>/
        dicoms/          (input  -- DICOMs live here)
        overlays/        (output, from output.visualizer)
        Textures/        (output, from output.exporter)
        Stars/           (output, from output.exporter)
        Inserts/         (output, from output.exporter)  <- user's "cylinders"
        metadata.json    (output, from output.exporter)

We reuse ``output.visualizer.generate_overlays`` and
``output.exporter.export_results`` *unchanged* by passing
``output_dir=<labeled_root>`` and ``series_name=<labeled_name>``. Those helpers
compose ``<labeled_root>/<labeled_name>/`` internally, which is exactly where
we want the annotation outputs to land -- right next to the ``dicoms/``
subfolder, not inside it.

The alternative (calling ``main.py:process_series`` directly) would not work:
that function derives ``series_name = os.path.basename(series_dir)``, so
passing ``series_dir=<labeled_root>/<labeled_name>/dicoms`` would cause every
output to be written under a spurious ``.../dicoms/overlays`` folder. Hence
this thin wrapper that mirrors the phase sequence but controls the output
layout explicitly.
"""

import os
from typing import Optional

from utils.logger import log


def annotate_labeled_series(
    labeled_root: str,
    labeled_name: str,
):
    """Run phases 0-6 for one labeled series and write outputs in-place.

    Parameters
    ----------
    labeled_root
        The parent directory containing all labeled folders (e.g.
        ``Desktop/CALIBRAMICS_TEST 2615_LABELED``).
    labeled_name
        Name of the labeled subfolder that holds ``dicoms/``.

    Returns
    -------
    ValidationReport on success, or ``None`` on any fatal failure. ``None``
    lets the batch caller keep processing the remaining series instead of
    aborting the whole run.
    """
    series_dir = os.path.join(labeled_root, labeled_name, "dicoms")
    if not os.path.isdir(series_dir):
        log.error(f"dicoms/ folder missing: {series_dir}")
        return None

    log.info("-" * 60)
    log.info(f"Annotating: {labeled_name}")

    # Clear previous annotation outputs before re-running. Every artifact
    # below is fully regenerated by this function, but only for the slices
    # the CURRENT run extracts — a re-run after a pipeline fix that narrows
    # a section window would otherwise leave stale ROI files from the old
    # run sitting next to the fresh ones (observed on 20251126 Q1/80kVp:
    # bogus-fragment Star16 ROIs for slices 51-73 survived a re-annotation
    # that correctly stopped at slice 50). dicoms/ is never touched.
    import shutil
    series_root = os.path.join(labeled_root, labeled_name)
    for artifact in ("overlays", "Textures", "Stars", "Inserts",
                     "coronal", "painted"):
        path = os.path.join(series_root, artifact)
        if os.path.isdir(path):
            shutil.rmtree(path, ignore_errors=True)
    meta_path = os.path.join(series_root, "metadata.json")
    if os.path.isfile(meta_path):
        try:
            os.remove(meta_path)
        except OSError:
            pass

    # Deferred imports: keep `label_series.py --no-annotate` fast and avoid
    # paying the cv2/numpy/scipy import cost when annotation is skipped. This
    # mirrors the same pattern main.py:process_series uses.
    from core.dicom_loader import load_series
    from core.phantom_detector import detect_phantom
    from core.section_classifier import classify_sections
    from core.rotation_detector import detect_rotation
    from core.roi_extractor import extract_rois
    from core.validator import validate_all
    from output.visualizer import generate_overlays
    from output.insert_painter import paint_insert_rois
    from output.exporter import export_results

    # Phases 0-5 are all-or-nothing: if any of them raise, we cannot produce
    # a meaningful validation/extraction result and must bail out.
    try:
        dv = load_series(series_dir)
        phantom = detect_phantom(dv)
        sections = classify_sections(dv, phantom)
        # Phase 2b: canonicalise upside-down phantom acquisitions before
        # subsequent phases consume the volume.
        from core.orientation_corrector import canonicalize_orientation
        canonicalize_orientation(dv, phantom, sections)
        # Phase 2c: trim each section to its inner physical-z window so the
        # kept volume is protocol-independent.
        from core.section_trim import trim_sections_to_inner_window
        trim_sections_to_inner_window(dv, sections, phantom=phantom)
        rotation = detect_rotation(dv, phantom, sections)
        extraction = extract_rois(dv, phantom, sections, rotation)
        validation = validate_all(dv, phantom, sections, extraction)
    except Exception as e:
        log.error(
            f"Phases 0-5 failed for {labeled_name}: {e}",
            exc_info=True,
        )
        return None

    # Overlays are best-effort: a render failure should not block the numeric
    # exports below (this matches main.py's existing tolerance).
    try:
        generate_overlays(
            dv, phantom, sections, extraction, labeled_root, labeled_name
        )
    except Exception as e:
        log.error(
            f"Overlay generation failed for {labeled_name}: {e}",
            exc_info=True,
        )

    try:
        paint_insert_rois(
            dv, phantom, sections, extraction, labeled_root, labeled_name
        )
    except Exception as e:
        log.error(
            f"Insert paint generation failed for {labeled_name}: {e}",
            exc_info=True,
        )

    try:
        from output.coronal_overlay import generate_coronal_overlay
        generate_coronal_overlay(
            dv, phantom, sections, labeled_root, labeled_name
        )
    except Exception as e:
        log.error(
            f"Coronal overlay generation failed for {labeled_name}: {e}",
            exc_info=True,
        )

    # export_results writes the .dcm ROI files and metadata.json. If this
    # fails we treat the whole annotation as failed so the batch report can
    # flag the series for re-processing.
    try:
        export_results(
            extraction, validation, labeled_root, labeled_name,
            source_metadata=dv.metadata,
        )
    except Exception as e:
        log.error(
            f"export_results failed for {labeled_name}: {e}",
            exc_info=True,
        )
        return None

    return validation
